def _written(keys: str) -> str:
    """CTRL+SHIFT+M -> "Ctrl+Mayús+M"."""
    return "+".join(_KEY_NAMES.get(part, part) for part in keys.split("+"))


def _act(action_id: str, label: str, keys: str, icon: str, sub: str = "") -> dict[str, str]:
    return {"id": action_id, "label": label, "sub": sub or _written(keys), "keys": keys, "icon": icon}


def _pack(pack_id: str, name: str, category: str, exe: str, color: str, icon: str, actions: list) -> dict[str, Any]:
    return {
        "id": pack_id,
        "name": name,
        "category": category,
        "exe": exe,
        "color": color,
        "icon": icon,
        "actions": [_act(*action) for action in actions],
    }


